#!/usr/bin/env python3
"""Build gallery data + thumbnails for Swap's Doodles.

Scans images/*.png, makes square webp/jpg thumbnails, extracts a colour
palette from each piece, and writes assets/gallery-data.js
"""
import json, os, glob
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG_DIR = os.path.join(ROOT, "images")
THUMB_DIR = os.path.join(IMG_DIR, "thumbs")
DATA_OUT = os.path.join(ROOT, "assets", "gallery-data.js")
TITLES_OUT = os.path.join(ROOT, "titles.json")

os.makedirs(THUMB_DIR, exist_ok=True)
os.makedirs(os.path.dirname(DATA_OUT), exist_ok=True)

titles = {}
if os.path.exists(TITLES_OUT):
    titles = json.load(open(TITLES_OUT))

COLLECTIONS = ["characters", "creatures", "moments"]
FALLBACK_TITLES = [
    "Untitled Doodle", "No Notes", "Wobbly But Fine", "Just Vibing",
    "Small Chaos", "Big Feeling", "Sunday Mode", "Side Quest",
]

def _dist(c1, c2):
    return sum((a - b) ** 2 for a, b in zip(c1, c2)) ** 0.5


def palette(im, n=4, bg_tol=34, spread=46):
    """Return up to n distinct, non-backdrop accent colours."""
    small = im.convert("RGB").resize((140, 140))
    q = small.quantize(colors=24, method=Image.MEDIANCUT)
    pal = q.getpalette()
    counts = sorted(q.getcolors(), reverse=True)

    bg = None
    if counts:
        idx = counts[0][1]
        bg = tuple(pal[idx * 3: idx * 3 + 3])

    out = []
    for count, idx in counts:
        rgb = tuple(pal[idx * 3: idx * 3 + 3])
        if bg and _dist(rgb, bg) < bg_tol:
            continue
        if rgb[0] > 246 and rgb[1] > 246 and rgb[2] > 246:
            continue
        if any(_dist(rgb, seen) < spread for seen in out):
            continue
        out.append(rgb)
        if len(out) >= n:
            break

    # never return fewer than 3 swatches
    if len(out) < 3 and bg:
        for count, idx in counts:
            rgb = tuple(pal[idx * 3: idx * 3 + 3])
            if any(_dist(rgb, seen) < 20 for seen in out):
                continue
            out.append(rgb)
            if len(out) >= 3:
                break

    return ["#%02x%02x%02x" % c for c in out]

items = []
files = sorted(
    glob.glob(os.path.join(IMG_DIR, "*.webp")) or glob.glob(os.path.join(IMG_DIR, "*.png"))
)
for i, path in enumerate(files, start=1):
    key = os.path.splitext(os.path.basename(path))[0]
    im = Image.open(path)
    w, h = im.size
    side = min(w, h)
    box = ((w - side) // 2, (h - side) // 2, (w - side) // 2 + side, (h - side) // 2 + side)

    thumb = im.convert("RGB").crop(box).resize((480, 480), Image.LANCZOS)
    thumb.save(os.path.join(THUMB_DIR, key + ".webp"), "WEBP", quality=80, method=6)

    meta = titles.get(key, {})
    n = int(key) if key.isdigit() else i
    items.append({
        "id": key,
        "n": n,
        "title": meta.get("title") or FALLBACK_TITLES[(n - 1) % len(FALLBACK_TITLES)],
        "collection": meta.get("collection", COLLECTIONS[(n - 1) % 3]),
        "src": "images/" + os.path.basename(path),
        "thumb": "images/thumbs/" + key + ".webp",
        "palette": palette(im),
        "w": w,
        "h": h,
    })

items.sort(key=lambda x: x["n"])
payload = json.dumps(items, indent=2)
with open(DATA_OUT, "w") as f:
    f.write("// generated by tools/build.py — do not edit by hand\n")
    f.write("window.GALLERY = " + payload + ";\n")

print(f"built {len(items)} pieces -> {DATA_OUT}")
for it in items:
    print(" ", it["id"], it["title"], it["collection"], " ".join(it["palette"]))
